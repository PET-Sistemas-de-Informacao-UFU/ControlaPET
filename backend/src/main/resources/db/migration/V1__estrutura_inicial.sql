-- Estrutura inicial para bancos PostgreSQL novos.
-- Bancos existentes precisam de comparacao e baseline manual antes da adocao.
CREATE TABLE users (
    id uuid PRIMARY KEY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    active boolean NOT NULL,
    password_changed_at timestamp,
    session_version bigint,
    created_at date NOT NULL,
    updated_at date
);

CREATE TABLE items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    description text,
    type varchar(255) NOT NULL,
    condition varchar(255) NOT NULL,
    total_quantity integer NOT NULL,
    stock_quantity integer NOT NULL,
    maintenance_quantity integer DEFAULT 0 NOT NULL,
    created_at date NOT NULL,
    updated_at date
);

CREATE TABLE loans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id),
    item_id bigint NOT NULL REFERENCES items(id),
    quantity integer NOT NULL,
    checkout_date timestamp NOT NULL,
    expected_return_date date NOT NULL,
    actual_return_date timestamp,
    status varchar(255) NOT NULL
);
CREATE INDEX idx_loans_status_expected_return ON loans (status, expected_return_date);

CREATE TABLE movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id),
    item_id bigint NOT NULL REFERENCES items(id),
    movement_type varchar(255) NOT NULL,
    quantity integer NOT NULL,
    notes varchar(255),
    movement_date timestamp NOT NULL
);

CREATE TABLE password_reset_tokens (
    id uuid PRIMARY KEY,
    token_hash varchar(64) NOT NULL UNIQUE,
    user_id uuid NOT NULL REFERENCES users(id),
    expires_at timestamp NOT NULL,
    used boolean NOT NULL
);

CREATE TABLE password_reset_audits (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id),
    event_type varchar(32) NOT NULL,
    request_ip varchar(64),
    created_at timestamp NOT NULL
);

CREATE TABLE defect_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES items(id),
    reported_by_id uuid NOT NULL REFERENCES users(id),
    description text NOT NULL,
    status varchar(255) NOT NULL,
    quantity integer,
    confirmed_quantity integer,
    reserved_quantity integer,
    stock_reserved_at timestamp,
    loan_id bigint REFERENCES loans(id),
    confirmed_by_id uuid REFERENCES users(id),
    confirmed_at timestamp,
    maintenance_started_at timestamp,
    created_at timestamp NOT NULL,
    closed_by_id uuid REFERENCES users(id),
    closed_at timestamp,
    resolution_notes text
);
CREATE INDEX idx_defect_report_item ON defect_reports (item_id);
CREATE INDEX idx_defect_report_loan_status ON defect_reports (loan_id, status);
CREATE INDEX idx_defect_report_status_created ON defect_reports (status, created_at);
